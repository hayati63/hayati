# دلار و تتر یک چیز را اندازه می‌گیرند؛ اگر دلار نبود تتر جایش می‌نشیند.
DOLLAR_FALLBACK = {"dollar": "usdt", "usdt": "dollar"}


def group_of(symbol, category):
    """گروه واقعی یک نماد — «بخشی» به زیربخشش شکسته می‌شود."""
    if category == "بخشی":
        return SYM_TO_SUB.get(symbol, "بخشی_سایر")
    return category


def gate(group, driver_state, proxy_of=None):
    """چراغ یک گروه از روی وضعیت محرک‌هایش.

    driver_state: نگاشت id محرک → 'بالا' / 'داخل' / 'زیر' / None
    proxy_of: نگاشت id محرک → گروهی که فعلاً جایش نشسته (اگر پروکسی باشد)

    خروجی: (چراغ, امتیاز, جزئیات). امتیاز وزنی بین ‎-1‎ و ‎+1‎ است؛
    محرکی که داده ندارد از مخرج حذف می‌شود، نه اینکه صفر حساب شود.

    **خودارجاعی.** تا وقتی محرکی با پروکسی پر می‌شود، ممکن است آن پروکسی
    خودِ همین گروه باشد — مثلاً چراغ «طلا» از اونس طلا می‌آید و اونس طلا
    فعلاً با دستهٔ «طلا» پروکسی شده. آن چراغ چیزی جز «طلا بالای باکس خودش
    است» نمی‌گوید و در جزئیات علامت می‌خورد.
    """
    exp = EXPOSURE.get(group)
    if not exp:
        return "بی‌نقشه", None, []
    proxy_of = proxy_of or {}
    val = {"بالا": 1.0, "داخل": 0.0, "زیر": -1.0}
    num = den = 0.0
    detail = []
    self_ref_w = 0.0
    for did, w in sorted(exp.items(), key=lambda kv: -kv[1]):
        st = driver_state.get(did)
        if st is None:
            alt = DOLLAR_FALLBACK.get(did)
            if alt:
                st = driver_state.get(alt)
                if st is not None:
                    did = alt
        circular = proxy_of.get(did) == group
        if circular:
            self_ref_w += w
        detail.append({"driver": did, "name": DRIVER_NAME.get(did, did),
                       "w": w, "state": st, "circular": circular})
        if st in val:
            num += w * val[st]
            den += w
    if den == 0:
        return "بدون داده", None, detail
    score = num / den
    light = "سبز" if score >= 0.5 else ("قرمز" if score <= -0.5 else "زرد")
    if self_ref_w >= 0.5:
        light = "خودارجاع"
    return light, score, detail


def coverage(real_ids):
    """چند محرک **دادهٔ واقعی** دارند — پروکسی حساب نمی‌شود."""
    have = sum(1 for d in DRIVERS if d["id"] in real_ids)
    return have, len(DRIVERS)
