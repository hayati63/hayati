from collections import Counter

# نمادهای پیوسته (۷ روز هفته) شکافی ندارند تا مرز از آن دربیاید. دلار،
# تتر و طلای ۱۸ عیار این‌طورند. برایشان دوشنبه می‌گذاریم چون چارتیکس
# برای ابزار پیوسته هفتهٔ ISO (دوشنبه) می‌کشد، و همان است که مصطفی
# نگاه می‌کند. اگر اکسپورت ۱W این‌ها برسد، این پیش‌فرض اندازه‌گیری می‌شود.
CONTINUOUS_ANCHOR = 0          # دوشنبه
MIN_GAP_SHARE = 0.55           # اگر روزِ غالب کمتر از این بود، پیوسته حسابش کن


def trading_weekdays(dates, share=0.02):
    """روزهای هفته‌ای که واقعاً کندل دارند."""
    cnt = Counter(d.weekday() for d in dates)
    return sorted(k for k, v in cnt.items() if v > len(dates) * share)


FUND_ANCHOR = 6          # یکشنبه — رجوع به توضیحِ weekly_backtest.week_key


def derive_anchor(dates):
    """(روزِ شروعِ هفته، اطمینان، پیوسته‌بودن).

    روزِ شروع = روزی که بیشترین بار **بعد از یک شکاف ≥۲ روز** می‌آید.
    برای ابزار ۵روزه این خیلی تمیز درمی‌آید (۹۴–۹۷٪). برای ابزار پیوسته
    شکاف فقط تعطیلی است، پس اطمینان می‌افتد و `CONTINUOUS_ANCHOR`
    برمی‌گردد.
    """
    ds = sorted(dates)
    if len(ds) < 20:
        return CONTINUOUS_ANCHOR, 0.0, True
    starts = Counter()
    for i, d in enumerate(ds):
        if i == 0 or (d - ds[i - 1]).days >= 2:
            starts[d.weekday()] += 1
    if not starts:
        return CONTINUOUS_ANCHOR, 0.0, True
    day, n = starts.most_common(1)[0]
    conf = n / sum(starts.values())
    # ابزار پیوسته: هر هفت روز کندل دارد
    if len(trading_weekdays(ds)) >= 7 or conf < MIN_GAP_SHARE:
        return CONTINUOUS_ANCHOR, conf, True
    # بازاری که شنبه باز می‌شود، بورس ایران است. آنجا پنجرهٔ باکس
    # یکشنبه→شنبه است (نه شنبه→چهارشنبه) — دلیلش در
    # weekly_backtest.week_key نوشته شده و اندازه‌گیری شده.
    if day == 5:
        return FUND_ANCHOR, conf, False
    return day, conf, False


def week_key_for(anchor):
    """تابعِ کلیدِ هفته برای یک مرزِ مشخص."""
    def key(d):
        back = (d.weekday() - anchor) % 7
        return d.fromordinal(d.toordinal() - back)
    return key
